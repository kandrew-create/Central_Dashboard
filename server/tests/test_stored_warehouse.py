    def value(self,query):
        return self._run(query).stdout.strip().splitlines()[-1]

    def refresh(self):
        return self._run('BEGIN; SET LOCAL ROLE scada_worker; SELECT warehouse.refresh_pending(1000); COMMIT;')

    def test_stored_grain_and_daily_equipment_summaries(self):
        self.assertEqual(self.value('SELECT count(*) FROM warehouse.fact_alarm_occurrence'),'0')
        self.assertEqual(self.value('SELECT count(*) FROM warehouse.refresh_queue'),'2')
        self.refresh()
        self.assertEqual(self.value('SELECT count(*),sum(saved_versions) FROM warehouse.fact_alarm_occurrence'),'2|3')
        self.assertEqual(self.value("SELECT relkind FROM pg_class WHERE oid='warehouse.fact_alarm_occurrence'::regclass"),'r')
        self.assertEqual(self.value("SELECT occurrences,saved_versions FROM reporting.alarm_daily_summary WHERE occurrence_date_utc='2026-10-20'"),'1|2')
        self.assertEqual(self.value('SELECT occurrences FROM reporting.alarm_daily_summary WHERE occurrence_date_utc IS NULL'),'1')

    def test_upgrade_downgrade_backfills_and_preserves_native_history(self):
        url=URL.create('postgresql+psycopg',username=os.environ['PGUSER'],password=os.environ.get('PGPASSWORD'),
            host=os.environ['PGHOST'],port=int(os.environ['PGPORT']),database=self.database)
        engine=create_engine(url,hide_parameters=True)
        try:
            with engine.begin() as db,patch.dict(os.environ,{'MIGRATION_DATABASE_URL':url.render_as_string(hide_password=False)}):
                cfg=Config(str(ROOT/'alembic.ini'));cfg.attributes['connection']=db
                command.stamp(cfg,'0012_shared_source_storage')
                before=db.exec_driver_sql('SELECT revision_id,md5(original_payload::text) FROM platform.alarm_event_revisions ORDER BY revision_id').all()
                oids=dict(db.exec_driver_sql("SELECT source_id,to_regclass(quote_ident(schema_name)||'.alarmhistory')::oid FROM platform.source_storage ORDER BY source_id").all())
                command.downgrade(cfg,'0010_alarm_warehouse')
                self.assertEqual(db.exec_driver_sql('SELECT count(*) FROM warehouse.fact_alarm_occurrence').scalar_one(),2)
                command.upgrade(cfg,'0012_shared_source_storage')
                self.assertEqual(db.exec_driver_sql('SELECT count(*) FROM warehouse.fact_alarm_occurrence').scalar_one(),2)
                self.assertEqual(db.exec_driver_sql('SELECT revision_id,md5(original_payload::text) FROM platform.alarm_event_revisions ORDER BY revision_id').all(),before)
                after=dict(db.exec_driver_sql("SELECT source_id,to_regclass(quote_ident(schema_name)||'.alarmhistory')::oid FROM platform.source_storage ORDER BY source_id").all())
                self.assertTrue(all(after.get(source)==oid for source,oid in oids.items()))
        finally:
            engine.dispose()

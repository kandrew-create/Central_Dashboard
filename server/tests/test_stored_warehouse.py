    def test_customer_rls_and_maintenance_permissions(self):
        other=revision_sql(revision=130)
        for n in (1,2,3,6,7,20): other=other.replace(uid(n),uid(n+100))
        self._run(batch_sql(upload=120,batch=121,customer=101,source=106,generation=107)+other)
        self.refresh()
